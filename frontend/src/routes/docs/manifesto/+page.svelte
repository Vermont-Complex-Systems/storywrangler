<h3>Background</h3>

<p>
    At the Vermont Complex Systems Institute, we aim to provide a platform that offers instruments to better understand collective attention from all kinds of ecological timeseries. These instruments are necessary to take different kinds of input from social media and other sociotechnical platforms by which modern societies distribute their attention, think Twitter, Reddit, Bluesky but also Wikipedia, Google Books, and so on. All of these, in a very reductive sense, can be modeled as ecological timeseries; words + amplification mechanism = collective attention.
</p>

<p>
    At the time, academia is confronted with the following tragedy of the commons; the bulk of computational work in academia is done by graduate students that come and go. In many cases, it falls on the shoulders of students to properly documents and ensure longevity of their works on the long run. There are an increasing number of platforms that can help with that, most notably Zeonodo that can provide digital object identifiers to computational works beyond that of papers.
</p>

<p>
    Yet, Zenodo is kind of a everything goes platform. We need a solution that is closer to communities; one that provide the tooling for individuals to feel compelled to share because they want to see their work being <em>used</em> and <em>recognized</em> by others. We need decentralized ecosystems of datasets that are alive and that are nurtured, similar to how forest and fisheries can be managed by communities.  For that, we need a place that people can nurture.
</p>

